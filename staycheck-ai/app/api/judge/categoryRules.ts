/**
 * カテゴリキーから、AIに渡す追加指示テキストを組み立てる。
 * "auto"（自動判定）や未定義のキーの場合は null を返し、
 * 従来通りAIに主題を推測させる(BASE_JUDGE_RULE側の一般ルールに従う)。
 */
export function buildCategoryInstruction(categoryKey: string): string | null {
  const def = CATEGORY_DEFINITIONS[categoryKey];
  if (!def) return null;

  const focusList = def.focusItems.map((item) => `- ${item}`).join("\n");

  return `## この写真のカテゴリ指定: ${def.label}

この写真は「${def.label}」を確認するために撮影されたことが、
アップロード時に人によって指定されている(推測ではなく確定情報)。

以下の項目のみを判定対象とし、checksにはこれらの項目だけを含めること
(冒頭に挙げた8観点など、これ以外の項目はchecksに含めなくてよい)。

${focusList}

${def.instruction ?? ""}

このカテゴリと無関係な項目(例: 玄関の写真でベッドの状態など)は、
そもそも判定対象外なので、写っていないことを理由に
"◇ 確認推奨" にはしないこと。

**一方で、このカテゴリが本来確認すべき対象そのものが写真に全く写っていない
場合は例外である。** 例えば「洗濯機」カテゴリなのに洗濯機やその部品が
写真のどこにも写っていない、「ブラインド」カテゴリなのにブラインドが
写真に写っていない、という場合は、"◇ 確認推奨" とし、summaryに
「指定されたカテゴリの対象が写真から確認できません」といった趣旨を
明記すること。これは撮影者が明示的にこのカテゴリを選んでいるにも
関わらず、その主題が写っていないという状況を意味するためである。

**checksの出力についてはこのカテゴリ指定が優先される。** 冒頭の8観点や
「checksは8観点を返すこと」という指示は、このカテゴリが指定されている
場合は無視し、上記の項目のみを返すこと。`;
}
